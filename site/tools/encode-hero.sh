#!/usr/bin/env bash
# Encode the opening demo's footage: one base stream clip + one lucy-2.5 render per
# effect, all frame-aligned, into small web files the player can switch between
# mid-playback. See site/CLIPS.md.
#
#   tools/encode-hero.sh <effects.tsv> [out-dir]
#
# effects.tsv: tab-separated, one clip per line, '#' comments allowed:
#   id <TAB> source-video <TAB> emoji <TAB> label <TAB> one-line description
# The first line must have id "base" (the original stream; emoji/label/description
# are used for the "Original" button). Source paths are relative to $SRC_DIR
# (default: the TSV's folder); the raw recordings are not committed.
#
# Every output is trimmed to the base clip's frame count, so all clips loop on the
# same frame. Keyframes every 15 frames (0.5 s) make a seek decode at most half a
# second of video: that is what lets a click land on the same moment instantly.
# hd = 960×540 (the player is never wider on desktop), sd = 640×360 for phones.
# Filenames carry a content hash, so the files can be cached forever.
set -euo pipefail

tsv=${1:?usage: encode-hero.sh <effects.tsv> [out-dir]}
here=$(cd "$(dirname "$0")/.." && pwd)
out=${2:-$here/public/clips/hero}
src_dir=${SRC_DIR:-$(cd "$(dirname "$tsv")" && pwd)}
CRF_HD=${CRF_HD:-32}
CRF_SD=${CRF_SD:-34}

command -v ffmpeg >/dev/null || { echo "needs ffmpeg"; exit 1; }
mkdir -p "$out"
work=$(mktemp -d)
trap 'mv "$work" "${TMPDIR:-/tmp}/encode-hero-done-$$" 2>/dev/null || true' EXIT

frames=""
entries=()
while IFS=$'\t' read -r id file emoji label desc; do
  [[ -z "${id// }" || $id == \#* ]] && continue
  in="$src_dir/$file"
  [[ -f $in ]] || { echo "missing: $in"; exit 1; }
  if [[ -z $frames ]]; then
    [[ $id == base ]] || { echo "first line must be the base clip"; exit 1; }
    frames=$(ffprobe -v error -select_streams v:0 -count_frames -show_entries stream=nb_read_frames -of csv=p=0 "$in")
    echo "base: $frames frames"
  fi
  enc() { # $1=width $2=height $3=crf $4=output
    ffmpeg -nostdin -v error -y -i "$in" -frames:v "$frames" -an \
      -vf "fps=30,scale=$1:$2:flags=lanczos,setsar=1,format=yuv420p" \
      -c:v libx264 -profile:v high -preset slow -crf "$3" \
      -g 15 -keyint_min 15 -sc_threshold 0 -movflags +faststart "$4"
  }
  enc 960 540 "$CRF_HD" "$work/$id.hd.mp4"
  enc 640 360 "$CRF_SD" "$work/$id.sd.mp4"
  ffmpeg -nostdin -v error -y -ss 10 -i "$in" -frames:v 1 -vf "scale=960:540:flags=lanczos" -q:v 5 "$work/$id.jpg"
  names=()
  for f in "$id.hd.mp4" "$id.sd.mp4" "$id.jpg"; do
    h=$(shasum -a 256 "$work/$f" | cut -c1-8)
    n="${f%%.*}.$h.${f#*.}"
    cp "$work/$f" "$out/$n"
    names+=("$n")
  done
  printf '  %-11s %6s KB hd  %6s KB sd\n' "$id" $(( $(stat -f%z "$work/$id.hd.mp4") / 1024 )) $(( $(stat -f%z "$work/$id.sd.mp4") / 1024 ))
  entries+=("$(ID="$id" EMOJI="$emoji" LABEL="$label" DESC="$desc" HD="${names[0]}" SD="${names[1]}" POSTER="${names[2]}" \
    node -e 'const e=process.env;process.stdout.write(JSON.stringify({id:e.ID,emoji:e.EMOJI,label:e.LABEL,description:e.DESC,hd:"/clips/hero/"+e.HD,sd:"/clips/hero/"+e.SD,poster:"/clips/hero/"+e.POSTER}))')")
done <"$tsv"

{
  echo '{'
  echo '  "_comment": "Generated by site/tools/encode-hero.sh. Real lucy-2.5 output; every clip has the same frame count and loops on the same frame.",'
  echo "  \"model\": \"lucy-2.5\","
  echo "  \"fps\": 30,"
  echo "  \"frames\": $frames,"
  echo "  \"duration\": $(node -e "console.log(+($frames/30).toFixed(4))"),"
  echo '  "clips": ['
  for i in "${!entries[@]}"; do
    sep=,; [[ $i -eq $((${#entries[@]} - 1)) ]] && sep=
    echo "    ${entries[$i]}$sep"
  done
  echo '  ]'
  echo '}'
} >"$out/manifest.json"
echo "wrote $out/manifest.json"
du -sh "$out"
